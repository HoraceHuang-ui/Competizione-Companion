// ---------------------------------------------------------------------------
// 覆盖式闪烁的进度计算（纯函数，便于单测）
//
// 两个组件都用它：
//   · 车损：碰撞时整块覆盖红色 —— 保持 0.1s，再用 0.3s 回到原样；
//   · 轮胎：冲击掉胎压时覆盖红色 —— 保持 0.8s，再用 1.3s 回到原样。
//
// 返回 0 = 刚命中（完全不透明、整块纯色），1 = 已完全回到原样。
// ---------------------------------------------------------------------------

/** 命中瞬间的覆盖不透明度：1 - progress */
export function flashProgress(elapsedMs: number, holdMs: number, fadeMs: number): number {
  // ⚠️ 非有限的时间一律当作"早就复原"（返回 1），**绝不能返回 0** ——
  // 0 表示"整块纯色"，而"从没命中过"的通道正是拿 -Infinity 当哨兵：
  // 一旦这里返回 0，那次冲击会把**所有**通道都刷成红色，并且永久停在那里
  // （因为 p < 1 会让 rAF 一直空转）。这是实测踩过的坑。
  if (!Number.isFinite(elapsedMs)) return 1
  if (elapsedMs <= holdMs) return 0
  if (fadeMs <= 0) return 1
  const k = (elapsedMs - holdMs) / fadeMs
  return k >= 1 ? 1 : k
}
